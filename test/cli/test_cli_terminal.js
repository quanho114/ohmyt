import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {Terminal} from '../../cli/terminal.js';

const input = new EventEmitter();
const output = Object.assign(new EventEmitter(), {columns: 80, rows: 24, write: text => {transcript += text;}});
let transcript = '', submitted;
const terminal = new Terminal(input, output);
terminal.onSubmit = text => {submitted = text;};
terminal.key('Xin chào 👋', {});
terminal.key('', {name: 'return', meta: true});
terminal.key('second line', {});
terminal.key('', {name: 'return'});
assert.equal(submitted, 'Xin chào 👋\nsecond line');
terminal.key('ac', {}); terminal.key('', {name: 'left'}); terminal.key('b', {}); terminal.key('', {name: 'return'});
assert.equal(submitted, 'abc');
terminal.key('', {name: 'paste-start'}); terminal.key('pasted', {}); terminal.key('\n', {name: 'enter'}); terminal.key('lines', {}); terminal.key('', {name: 'paste-end'});
assert.equal(submitted, 'abc', 'Paste must not submit');
terminal.key('', {name: 'return'}); assert.equal(submitted, 'pasted\nlines');
const answer = terminal.question('Allow once? [y/N]');
terminal.key('', {name: 'return'});
assert.equal(await answer, '');
terminal.key('unsent draft', {});
const controller = new AbortController();
const expired = terminal.question('Remote approval', controller.signal);
controller.abort(); assert.equal(await expired, ''); assert.equal(terminal.draft, 'unsent draft');
terminal.key('', {name: 'u', ctrl: true});
const picker = terminal.choose('Model', [{label: 'First model', value: 'one'}, {label: 'Second model', value: 'two'}]);
terminal.key('', {name: 'down'}); terminal.key('', {name: 'return'});
assert.equal(await picker, 'two');
const filtered = terminal.choose('Model', [{label: 'First model', value: 'one'}, {label: 'Second model', value: 'two'}]);
terminal.key('Second', {}); terminal.key('', {name: 'return'});
assert.equal(await filtered, 'two');
terminal.key('/sta', {}); terminal.key('', {name: 'return'});
assert.equal(terminal.draft, '/status');
terminal.key('', {name: 'return'}); assert.equal(submitted, '/status');
terminal.setLive('\x1b]52;c;secret\x07hello');
assert(!transcript.includes('secret'));
output.columns = 40; terminal.draw(); terminal.flushLive();
assert(transcript.includes('hello'));
console.log('PASS terminal multiline, safe default prompt, command completion, escape sanitation and resize');
