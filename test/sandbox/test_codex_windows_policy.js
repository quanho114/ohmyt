import assert from 'node:assert/strict';
import {buildCodexWindowsPolicy,buildCodexWindowsArguments,CODEX_WINDOWS_SUPPORTED_VERSION} from '../../server/sandbox/codex-windows.js';
assert.equal(CODEX_WINDOWS_SUPPORTED_VERSION,'0.164.0');
const options={workspaceRoot:'C:\\project',runtimeRoots:['C:\\runtime'],denyPaths:['C:\\project\\.env','C:\\project\\private']};
const policy=buildCodexWindowsPolicy(options);
assert.match(policy,/sandbox = "elevated"/);
assert.match(policy,/enabled = false/);
assert.match(policy,/inherit = "none"/);
assert(policy.includes('"C:\\\\project" = "write"'));
assert(policy.includes('"C:\\\\project\\\\.env" = "none"'));
assert(!policy.includes('extends'));
assert(!policy.includes(':workspace'));
assert(!policy.includes(':root'));
const hostRead=buildCodexWindowsPolicy({...options,allowHostRead:true});
assert(hostRead.includes('\":root\" = \"read\"'));
assert(hostRead.includes('\"C:\\\\project\\\\.env\" = \"none\"'));
assert.throws(()=>buildCodexWindowsPolicy({...options,allowHostRead:'true'}),/boolean/);
const command=buildCodexWindowsArguments({...options,argv:['node.exe','-e','console.log("quote; exact")']});
assert.deepEqual(command.args.slice(-3),['node.exe','-e','console.log("quote; exact")']);
assert.equal(command.policy,policy);
for(const workspaceRoot of ['relative','\\\\server\\share','\\\\?\\C:\\project','C:\\bad\0path']) assert.throws(()=>buildCodexWindowsPolicy({workspaceRoot}),/local absolute/);
assert.throws(()=>buildCodexWindowsArguments({...options,argv:[]}),/argv/);
console.log('Codex Windows strict policy builder passed (not an execution/isolation test)');
