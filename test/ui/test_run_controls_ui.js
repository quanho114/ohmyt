import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from 'vite';
const server=await createServer({server:{port:0,host:'127.0.0.1',hmr:false},logLevel:'error'});
let browser;
try{
 await server.listen();browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage();
 await page.clock.install();
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/run-controls.html`);
 const count=async n=>page.waitForFunction(n=>window.controlsFixture?.pending.length===n,n);
 const resolve=async(index,id)=>page.evaluate(([index,id])=>window.controlsFixture.resolve(index,id),[index,id]);
 const state=()=>page.locator('output').textContent().then(JSON.parse);
 await count(1);
 await page.clock.runFor(3000);
 assert.equal(await page.evaluate(()=>window.controlsFixture.pending.length),1,'Slow polls must not overlap');
 await page.getByRole('button',{name:'Cancel pending'}).click();
 await page.evaluate(()=>window.controlsFixture.finish());await count(2);
 await resolve(1,null);await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).busy===false);
 await resolve(0,'stale-run');
 assert.equal((await state()).runId,null,'A poll started before cancellation must not restore the old run');
 // Leaving and returning to the same session must invalidate the first visit.
 await page.clock.runFor(1000);await count(3);
 await page.getByRole('button',{name:'Switch',exact:true}).click();await count(4);
 await page.getByRole('button',{name:'Switch',exact:true}).click();await count(5);
 await resolve(4,'new-run');await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).runId==='new-run');
 await resolve(2,'old-visit');await resolve(3,'other-session');
 assert.equal((await state()).runId,'new-run');
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).requests===1);
 await page.evaluate(()=>{void window.controlsFixture.answer();void window.controlsFixture.answer();});
 assert.equal(await page.evaluate(()=>window.controlsFixture.answers.length),1,'One answer may be submitted at a time, including the same render');
 await page.getByRole('button',{name:'Switch',exact:true}).click();
 await page.getByRole('button',{name:'Switch',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).requests===1);
 await page.evaluate(()=>{void window.controlsFixture.answer();});
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).inputBusy===true);
 assert.equal(await page.evaluate(()=>window.controlsFixture.answers.length),2);
 await page.evaluate(()=>window.controlsFixture.finishAnswer(0));
 assert.equal(await page.evaluate(()=>window.controlsFixture.continuations.length),0,'An answer from a previous visit cannot open a project in the current visit');
 assert.equal((await state()).inputBusy,true,'An old answer must not clear the current answer busy state');
 await page.evaluate(()=>window.controlsFixture.finishAnswer(1));
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).inputBusy===false);
 assert.equal(await page.evaluate(()=>window.controlsFixture.continuations.length),1);
 await page.evaluate(()=>window.controlsFixture.setPollFailure(true));await page.clock.runFor(800);
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).inputError==='Temporary poll failure');
 await page.evaluate(()=>window.controlsFixture.setPollFailure(false));await page.clock.runFor(800);
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).inputError==='',{},{timeout:2000});
 await page.evaluate(()=>{void window.controlsFixture.answer();});
 await page.waitForFunction(()=>window.controlsFixture.answers.length===3);
 await page.evaluate(()=>window.controlsFixture.failAnswer(2));
 await page.waitForFunction(()=>JSON.parse(document.querySelector('output').textContent).inputError==='Answer failed');
 await page.clock.runFor(800);
 assert.equal((await state()).inputError,'Answer failed','A successful poll must preserve an answer submission error');
 console.log('PASS chat controls: bounded polling, stale response fencing, answer dedupe, session revisit and poll recovery');
}finally{await browser?.close();await server.close();}
