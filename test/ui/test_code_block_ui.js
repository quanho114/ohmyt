import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from 'vite';
import fs from 'node:fs/promises';
const server=await createServer({server:{port:0,host:'127.0.0.1',hmr:false},logLevel:'error'});
let browser;
try {
 await server.listen();browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:800},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/code-block.html`);
 const wrap=page.getByRole('button',{name:'Wrap lines',exact:true});await wrap.waitFor();
 assert.equal(await page.locator('.code-numbered-line').count(),4);
 assert.equal(await page.locator('.code-header-actions button').count(),3,'Reference toolbar has wrap, download and copy icons');
 assert.equal(await page.locator('.content-block-header').evaluate(el=>getComputedStyle(el).borderBottomWidth),'0px');
 assert.equal(await page.locator('.code-line-number').first().evaluate(el=>getComputedStyle(el).borderRightWidth),'0px');
 await page.screenshot({path:'/tmp/ohmyt-code-block-refined.png'});
 assert.equal(await page.locator('.code-line-text .hljs-comment').count(),2,'Multiline syntax survives line splitting');
 const area=page.locator('.code-scroll-area');
 assert(await area.evaluate(el=>el.scrollWidth>el.clientWidth),'Long source initially scrolls horizontally');
 await wrap.click();assert.equal(await wrap.getAttribute('aria-pressed'),'true');
 assert(await area.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Wrapped source fits viewport');
 const line=page.locator('.code-numbered-line').nth(2);
 assert((await line.boundingBox()).height>40,'Long line wraps across several visual rows');
 assert.equal(await line.locator('.code-line-number').textContent(),'3');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download code',exact:true}).click();
 const file=await download;assert.equal(file.suggestedFilename(),'example.ts');
 const value=await fs.readFile(await file.path(),'utf8');
 assert.equal(value,'/* first\nsecond */\nconst message = "'+'long source '.repeat(30)+'";\n','Download preserves original source');
 await page.context().grantPermissions(['clipboard-read','clipboard-write']);
 await page.getByRole('button',{name:'Copy code',exact:true}).click();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),value);
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/code-block.html?long`);
 const expand=page.getByRole('button',{name:'Expand code',exact:true});await expand.waitFor();
 assert.equal(await expand.evaluate(el=>Boolean(el.closest('.content-block-header .code-header-actions'))),true);
 assert.equal(await page.locator('.code-block-footer').count(),0);
 await expand.click();assert.equal(await page.getByRole('button',{name:'Collapse code',exact:true}).getAttribute('aria-expanded'),'true');
 await page.getByRole('button',{name:'Collapse code',exact:true}).click();
 assert.equal(await page.locator('.content-block').evaluate(el=>el.classList.contains('is-expanded')),false);
 assert.deepEqual(errors,[]);
 console.log('PASS code block: wrapping, aligned line numbers, multiline highlighting, exact download and copy');
} finally {await browser?.close();await server.close();}
