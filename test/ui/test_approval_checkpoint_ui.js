import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from 'vite';
const server=await createServer({server:{port:0,host:'127.0.0.1',hmr:false},logLevel:'error'});let browser;
try{
 await server.listen();browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/approval-checkpoint.html`);
 const dialog=page.getByRole('dialog');await dialog.waitFor();
 await page.getByRole('heading',{name:'Xem các tab trình duyệt'}).waitFor();
 await page.getByText('Các tab được chia sẻ với sky',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Từ chối',exact:true}).evaluate(el=>el===document.activeElement),true);
 const rect=await dialog.boundingBox();assert(rect.x>=0&&rect.width<=390);
 assert(rect.height<360,'Read-only approval stays compact');
 await page.waitForTimeout(180);await page.screenshot({path:'/tmp/ohmyt-approval-compact.png'});
 await page.getByRole('button',{name:'Cho phép một lần',exact:true}).click();
 assert.equal(await page.locator('output').textContent(),'ALLOW_ONCE');
 await page.getByRole('button',{name:'New request',exact:true}).click();
 await page.getByLabel('Ghi nhớ quyền này trong chat này',{exact:true}).check();
 await page.getByRole('button',{name:'Cho phép và ghi nhớ',exact:true}).click();
 assert.equal(await page.locator('output').textContent(),'ALLOW_ALWAYS');
 await page.getByRole('button',{name:'New request',exact:true}).click();
 assert.equal(await page.getByRole('checkbox').isChecked(),false,'Remember resets for each request');
 await page.keyboard.press('Escape');assert.equal(await page.locator('output').textContent(),'DENY');
 await page.getByRole('button',{name:'Command',exact:true}).click();
 await page.getByText('Lệnh có thể thay đổi tệp hoặc trạng thái hệ thống.',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('Ghi nhớ quyền này trong dự án này').count(),1);
 await page.getByText('Chi tiết kỹ thuật',{exact:true}).click();
 await page.getByText('shell_exec',{exact:true}).waitFor();
 assert.equal(await dialog.locator('script').count(),0);
 await page.screenshot({path:'/tmp/ohmyt-approval-checkpoint.png'});
 await page.getByRole('button',{name:'Từ chối và đóng',exact:true}).click();assert.equal(await page.locator('output').textContent(),'DENY');
 const assertContained = async () => {
  const bounds = await dialog.boundingBox(), viewport = page.viewportSize();
  assert(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= viewport.width && bounds.y + bounds.height <= viewport.height, 'Dialog fits the viewport');
  assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true, 'No horizontal dialog overflow');
  const footer = await dialog.locator('footer').boundingBox();
  assert(footer.y >= bounds.y && footer.y + footer.height <= bounds.y + bounds.height, 'Approval actions stay visible');
 };
 await page.getByRole('button',{name:'HTML preview',exact:true}).click();
 await dialog.getByRole('heading',{name:'Tạo bản xem trước HTML',exact:true}).waitFor();
 await dialog.getByText('bo-nong-dan.html',{exact:true}).waitFor();
 assert.match(await dialog.locator('.approval-file span').textContent(), /HTML · [\d,.]+ KB/);
 assert.equal(await dialog.locator('.approval-details').evaluate(el=>el.open),false);
 assert(!(await dialog.locator('.approval-target').textContent()).includes('<!DOCTYPE'), 'Generated HTML is not the approval summary');
 assert((await dialog.boundingBox()).height < 500, 'Large HTML keeps a compact summary');
 await assertContained();
 for (const viewport of [{width:320,height:480},{width:844,height:390}]) {
  await page.setViewportSize(viewport);
  await assertContained();
 }
 await page.setViewportSize({width:1440,height:900});
 await page.waitForTimeout(180);
 await page.screenshot({path:'/tmp/ohmyt-approval-html-desktop.png'});
 await dialog.getByText('Xem mã HTML và chi tiết',{exact:true}).click();
 const source = dialog.getByLabel('Mã HTML',{exact:true});
 assert((await source.textContent()).startsWith('<!DOCTYPE html>'), 'Source can be read directly without JSON escapes');
 await dialog.getByText('Tham số gốc',{exact:true}).click();
 const raw = JSON.parse(await dialog.getByLabel('Tham số công cụ',{exact:true}).textContent());
 assert.equal(await source.textContent(),raw.input.content);
 assert(raw.input.content.length > 40000, 'Full source remains reviewable');
 assert.equal(raw.target,raw.input.content, 'Actual target and input remain intact');
 assert.equal(await dialog.locator('script, iframe').count(),0);
 assert.equal(await page.evaluate(()=>window.INJECTED),undefined, 'Approval never executes generated HTML');
 await assertContained();
 await page.setViewportSize({width:390,height:600});
 await assertContained();
 await dialog.getByText('Tham số gốc',{exact:true}).click();
 await source.evaluate(el=>{el.scrollTop=el.scrollHeight;});
 await assertContained();
 await page.screenshot({path:'/tmp/ohmyt-approval-html-mobile-details.png'});
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'));
 await dialog.getByText('Xem mã HTML và chi tiết',{exact:true}).click();
 await assertContained();
 await page.screenshot({path:'/tmp/ohmyt-approval-html-mobile-dark.png'});
 await page.getByRole('button',{name:'Cho phép một lần',exact:true}).click();
 assert.equal(await page.locator('output').textContent(),'ALLOW_ONCE');
 await page.getByRole('button',{name:'Unknown tool',exact:true}).click();
 await dialog.getByRole('heading',{name:'Cho phép dùng công cụ?',exact:true}).waitFor();
 assert.equal(await dialog.locator('.approval-tool-name').textContent(),'connector_custom_tool');
 assert((await dialog.locator('.approval-target').textContent()).length < 350, 'Unknown tool payloads cannot fill the summary');
 await assertContained();
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('output').textContent(),'DENY');
 assert.deepEqual(errors,[]);console.log('PASS approval checkpoint: decisions, scope, reset, Escape, large HTML/unknown-tool summaries, full escaped parameters and desktop/mobile layout');
}finally{await browser?.close();await server.close();}
