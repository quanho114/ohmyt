import assert from 'node:assert/strict';
import {activityTimeline} from '../../src/harness/activityTimeline.ts';
import {reasoningPreview} from '../../src/vendor/activity-summary/index.ts';
import type {ToolCallItem} from '../../src/types.ts';
const tool=(id:string,offset?:number):ToolCallItem=>({id,name:'fs_read',input:{},status:'completed',reasoningOffset:offset});
const reasoning='First thought.\nSecond thought.';
const entries=activityTimeline(reasoning,[tool('a',15),tool('b',15)]);
assert.deepEqual(entries.map(e=>e.kind),['reasoning','tool','tool','reasoning']);
assert.equal(entries.filter(e=>e.kind==='reasoning').map(e=>e.text).join(''),reasoning);
assert.equal(entries.at(-1)?.kind==='reasoning' && entries.at(-1)?.tail,true);
assert.deepEqual(activityTimeline(reasoning,[tool('legacy')]).map(e=>e.kind),['reasoning','tool']);
assert.deepEqual(activityTimeline('',[tool('a',0)]).map(e=>e.kind),['tool']);
assert.equal(activityTimeline(reasoning,[tool('bad',-20)])[0].kind,'tool');
assert.equal(activityTimeline(reasoning,[tool('bad',NaN)])[0].kind,'reasoning');
assert.equal(reasoningPreview('**Read files**\n\n**Check output**\nPartial',true),'Check output');
assert.equal(reasoningPreview('Partial line',true),'');
assert.equal(reasoningPreview('## Read files\nDetails',false),'Read files');
assert.equal(reasoningPreview('<!-- hidden -->\n',true),'');
assert.equal(reasoningPreview('One\r\n\r\nTwo\r\nPartial',true),'Two');
console.log('Activity timeline ordering, legacy receipts and stable reasoning previews passed.');
