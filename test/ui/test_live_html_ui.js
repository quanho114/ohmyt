import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from 'vite';
import {htmlDraft} from '../../shared/html_draft.js';
assert.deepEqual(htmlDraft('{"name":"a.html","content":"<h1>Xin\\nchào\\u0021'),{name:'a.html',content:'<h1>Xin\nchào!'});
assert.equal(htmlDraft('{"name":"a.html"}'),null);
assert.equal(htmlDraft('{"content":"A\\u00').content,'A');
assert.equal(htmlDraft('{"content":"A\\').content,'A');
assert.equal(htmlDraft('x'.repeat(2200001)),null);
const server=await createServer({server:{port:0,host:'127.0.0.1',hmr:false},logLevel:'error'});
let browser;
try{
 await server.listen();browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage();
 await page.addInitScript(()=>{window.electronAPI={writeClipboard:async text=>{window.copiedHtml=text;}};});
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/live-html.html`);
 const live=page.getByRole('region',{name:'HTML đang tạo'});
 await live.getByRole('tabpanel',{name:'Code HTML'}).waitFor();
 assert.equal(await live.locator('iframe').count(),0,'Partial HTML never executes');
 assert.equal(await live.getByRole('tab',{name:'Preview',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'Append',exact:true}).click();
 await live.locator('pre').filter({hasText:'Xin chào'}).waitFor();
 await page.getByRole('button',{name:'Complete',exact:true}).click();
 assert.equal(await live.locator('iframe').count(),0,'Completion keeps Code visible; preview is user initiated');
 assert.equal(await live.locator('.html-code-gutter').count(),4);
 assert((await live.locator('.hljs-name').count())>0,'HTML tags have syntax highlighting');
 await page.screenshot({path:'/tmp/ohmyt-live-html-colors.png'});
 await live.getByRole('tab',{name:'Preview',exact:true}).click();
 await live.locator('iframe').waitFor();
 assert.equal(await live.locator('iframe').getAttribute('sandbox'),'allow-scripts');
 await live.getByRole('tab',{name:'Code',exact:true}).click();await live.locator('pre').waitFor();
 await page.getByRole('button',{name:'Code',exact:true}).click();
 assert.equal(await page.locator('.html-artifact-actions').getByRole('button',{name:'Code',exact:true}).locator('svg').count(),1,'File card has one Code icon');
 const dialog=page.getByRole('dialog');await dialog.locator('pre').waitFor();
 await dialog.getByRole('button',{name:'Copy code',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.copiedHtml),'<style>\nh1 { color: coral; }\n</style>\n<h1>Xin chào</h1>');
 await dialog.getByText('Đã sao chép',{exact:true}).waitFor();
 assert.equal(await dialog.locator('.html-copy-control').getAttribute('data-state'),'copied');
 await page.waitForFunction(()=>document.querySelector('.html-editor-dialog .html-copy-control')?.getAttribute('data-state')==='idle');
 await dialog.getByRole('button',{name:'Copy code',exact:true}).getByText('Copy code',{exact:true}).waitFor();
 assert.equal(await dialog.locator('iframe').count(),0);
 assert.equal(await dialog.getByRole('button',{name:'Ngắt dòng',exact:true}).count(),0);
 await dialog.locator('.html-code-source').first().evaluate(node=>{node.textContent='Long HTML source '.repeat(150);});
 assert.equal(await dialog.locator('pre').evaluate(node=>node.scrollWidth>node.clientWidth),true,'Long source scrolls horizontally by default');
 const row=await dialog.locator('.html-code-row').first().boundingBox();
 assert(row.height<30,'Source stays on its original line');
 await dialog.getByRole('tab',{name:'Preview',exact:true}).click();await dialog.locator('iframe').waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 console.log('PASS live HTML: partial decoding, live code, no draft execution, receipt-gated preview, final code tab and mobile width');
}finally{await browser?.close();await server.close();}
