import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {createDaemon} from '../../server/index.js';

const temp=fs.mkdtempSync(path.join(os.tmpdir(),'ohmyt-connector-ui-'));
const daemon=createDaemon({dbPath:':memory:',dataDir:temp,port:0});
let browser;
try {
  const {port}=await daemon.start();
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({locale:'vi-VN',reducedMotion:'reduce',viewport:{width:1280,height:850}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${port}/#settings/connectors`);
  await page.getByText('Chưa có kết nối',{exact:true}).waitFor();
  await page.screenshot({path:'/tmp/ohmyt-connections-empty.png'});
  await page.getByRole('button',{name:'Thêm kết nối',exact:true}).click();
  assert.equal(await page.getByLabel('ID kết nối',{exact:true}).count(),0);
  assert.equal(await page.getByLabel('Giao thức',{exact:true}).count(),0);
  assert.equal(await page.getByLabel('Mã truy cập',{exact:true}).isVisible(),false);
  await page.getByLabel('Tên kết nối',{exact:true}).fill('Công cụ công việc');
  await page.getByLabel('Địa chỉ dịch vụ',{exact:true}).fill('http://127.0.0.1:9/mcp?invalid=1');
  await page.getByRole('button',{name:'Lưu kết nối',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByLabel('Tên kết nối',{exact:true}).inputValue(),'Công cụ công việc','Failed saves keep the draft');
  assert.equal(daemon.harness.connectors.list().length,0);
  await page.getByLabel('Địa chỉ dịch vụ',{exact:true}).fill('http://127.0.0.1:9/mcp');
  await page.locator('.connector-auth summary').click();
  await page.getByLabel('Mã truy cập',{exact:true}).fill('fixture-secret');
  await page.getByRole('button',{name:'Lưu kết nối',exact:true}).click();
  await page.locator('.connector-row').waitFor();
  const original=daemon.harness.connectors.list()[0];
  assert.match(original.id,/^connection_[a-f0-9]{32}$/);assert.equal(original.hasToken,true);
  await page.locator('.connector-row').getByRole('button',{name:'Sửa',exact:true}).click();
  assert.equal(await page.getByLabel('Mã truy cập',{exact:true}).inputValue(),'','Saved credentials never populate the form');
  await page.getByLabel('Tên kết nối',{exact:true}).fill('Tài liệu công việc');
  await page.getByRole('button',{name:'Lưu kết nối',exact:true}).click();
  await page.getByText('Tài liệu công việc',{exact:true}).waitFor();
  const edited=daemon.harness.connectors.list()[0];assert.equal(edited.id,original.id);assert.equal(edited.revision,2);assert.equal(edited.hasToken,true);
  await page.locator('.connector-row').getByRole('button',{name:'Kiểm tra',exact:true}).click();
  await page.getByRole('alert').waitFor();
  await page.getByRole('button',{name:'Thêm kết nối',exact:true}).click();
  await page.getByLabel('Tên kết nối',{exact:true}).fill('Công cụ trên máy');
  await page.screenshot({path:'/tmp/ohmyt-connections-form.png'});
  await page.getByRole('button',{name:'Trên máy này',exact:true}).click();
  await page.getByLabel('Chương trình',{exact:true}).fill(process.execPath);
  await page.getByLabel('Tham số',{exact:true}).fill(path.resolve('test/fixtures/harness/mcp-server.js'));
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'/tmp/ohmyt-connections-mobile-dark.png'});
  await page.getByRole('button',{name:'Lưu kết nối',exact:true}).click();
  const local=page.locator('.connector-row').filter({hasText:'Công cụ trên máy'});
  await local.waitFor();
  await local.getByRole('button',{name:'Kiểm tra',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Kiểm tra kết nối thành công.'}).waitFor();
  await local.getByRole('button',{name:'Kết nối',exact:true}).click();
  await local.getByText('Đã kết nối',{exact:true}).waitFor();
  assert(daemon.tools.get(`mcp__${daemon.harness.connectors.list().find(c=>c.name==='Công cụ trên máy').id}__echo`));
  await local.getByRole('button',{name:'Ngắt kết nối',exact:true}).click();
  await local.getByText('Chưa kết nối',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Thêm kết nối',exact:true}).click();
  await page.getByLabel('Tên kết nối',{exact:true}).fill('Draft');
  await page.getByLabel('Tên kết nối',{exact:true}).press('Escape');
  await page.locator('.connector-heading').waitFor();
  assert.equal(await page.getByRole('button',{name:'Thêm kết nối',exact:true}).evaluate(e=>e===document.activeElement),true);
  assert.deepEqual(errors,[]);
  console.log('PASS connector UI: progressive fields, generated IDs, draft/error handling, token retention, revisions, real MCP test/connect/disconnect, mobile layout and keyboard return');
} finally {await browser?.close();await daemon.stop();fs.rmSync(temp,{recursive:true,force:true});}
